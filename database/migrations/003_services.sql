CREATE TABLE IF NOT EXISTS chp_sessions (
 token_hash CHAR(64) PRIMARY KEY, user_id INT NOT NULL, expires_at DATETIME NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, INDEX idx_session_user (user_id),
 FOREIGN KEY (user_id) REFERENCES chp_users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS chp_account_tokens (
 token_hash CHAR(64) PRIMARY KEY, user_id INT NOT NULL, purpose ENUM('verify','reset') NOT NULL,
 expires_at DATETIME NOT NULL, FOREIGN KEY (user_id) REFERENCES chp_users(id) ON DELETE CASCADE,
 UNIQUE KEY unique_account_purpose (user_id,purpose)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS chp_notifications (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, message VARCHAR(1500) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, INDEX idx_notification_user (user_id,id),
 FOREIGN KEY (user_id) REFERENCES chp_users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS chp_audit_log (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, actor_id INT NULL, action VARCHAR(100) NOT NULL,
 entity VARCHAR(30) NOT NULL, entity_id INT NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (actor_id) REFERENCES chp_users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS chp_mail_outbox (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, recipient VARCHAR(190) NOT NULL,
 subject VARCHAR(200) NOT NULL, body TEXT NOT NULL, attempts INT NOT NULL DEFAULT 0,
 sent_at DATETIME NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS chp_event_requests (
 user_id INT NOT NULL, request_key VARCHAR(80) NOT NULL, event_id INT NOT NULL,
 PRIMARY KEY (user_id,request_key),
 FOREIGN KEY (user_id) REFERENCES chp_users(id) ON DELETE CASCADE,
 FOREIGN KEY (event_id) REFERENCES chp_events(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
